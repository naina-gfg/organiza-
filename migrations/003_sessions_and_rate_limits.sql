-- Executar exclusivamente com role administrativa/migradora (ex.: via DIRECT_URL).

BEGIN;

CREATE TABLE IF NOT EXISTS public.sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_sessions_user_id
  ON public.sessions (user_id);

CREATE INDEX IF NOT EXISTS idx_sessions_expires_at
  ON public.sessions (expires_at);

CREATE TABLE IF NOT EXISTS public.rate_limits (
  rate_key TEXT PRIMARY KEY,
  attempts INTEGER NOT NULL DEFAULT 0,
  window_expires_at BIGINT NOT NULL,
  blocked_until BIGINT
);

CREATE INDEX IF NOT EXISTS idx_rate_limits_window_expires
  ON public.rate_limits (window_expires_at, blocked_until);

COMMIT;
