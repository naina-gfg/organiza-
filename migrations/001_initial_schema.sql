-- nunca com a role de runtime da aplicacao.

BEGIN;

CREATE TABLE IF NOT EXISTS public.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.disciplines (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_disciplines_id_user UNIQUE (id, user_id)
);

CREATE TABLE IF NOT EXISTS public.tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  discipline_id INTEGER,
  title TEXT NOT NULL,
  description TEXT,
  due_date TEXT,
  priority TEXT NOT NULL DEFAULT 'Média',
  status TEXT NOT NULL DEFAULT 'Pendente',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Garante em nivel de banco que:
  -- 1) a tarefa so pode referenciar disciplina do mesmo user_id (MATCH SIMPLE permite discipline_id NULL);
  -- 2) ao excluir a disciplina, apenas discipline_id vira NULL e a tarefa e preservada.
  -- Requer PostgreSQL 15+ (compativel com Supabase e PostgreSQL 17).
  CONSTRAINT fk_tasks_discipline_owner
    FOREIGN KEY (discipline_id, user_id)
    REFERENCES public.disciplines (id, user_id)
    ON DELETE SET NULL (discipline_id)
);

-- Indices para consultas filtradas por proprietario e ordenacao padrao (Ordem atual)
CREATE INDEX IF NOT EXISTS idx_disciplines_user_name
  ON public.disciplines (user_id, name, id);

CREATE INDEX IF NOT EXISTS idx_tasks_user_id
  ON public.tasks (user_id);

CREATE INDEX IF NOT EXISTS idx_tasks_user_discipline
  ON public.tasks (user_id, discipline_id);

CREATE INDEX IF NOT EXISTS idx_tasks_user_default_order
  ON public.tasks (user_id, status, priority, due_date, id);

COMMIT;
